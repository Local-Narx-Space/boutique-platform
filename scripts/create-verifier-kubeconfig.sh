#!/usr/bin/env bash
# Admin-only bootstrap: finite-lived client certificate for read-only verification.
set -euo pipefail
umask 077
ENVIRONMENT=${1:-}
case "$ENVIRONMENT" in dev|staging|production) ;; *) echo 'Usage: create-verifier-kubeconfig.sh dev|staging|production [context]' >&2; exit 2;; esac
CONTEXT=${2:-kind-mega-local}
for executable in kubectl openssl base64; do command -v "$executable" >/dev/null; done
DIRECTORY="$HOME/.kube/boutique-verification"
mkdir -p "$DIRECTORY"
chmod 700 "$DIRECTORY"
OUTPUT="$DIRECTORY/$ENVIRONMENT.config"
if [ -e "$OUTPUT" ]; then
  echo "Refusing to overwrite $OUTPUT. Move it to a protected backup path before intentional rotation." >&2
  exit 1
fi
TEMPORARY=$(mktemp -d "$DIRECTORY/issue-XXXXXX")
trap 'rm -rf "$TEMPORARY"' EXIT
IDENTITY="boutique:jenkins-verifier:$ENVIRONMENT"
CSR="boutique-verifier-$ENVIRONMENT-$(date +%s)-$(openssl rand -hex 4)"
API=$(kubectl --context "$CONTEXT" config view --minify -o jsonpath='{.clusters[0].cluster.server}')
case "$API" in https://*) ;; *) echo 'A TLS Kubernetes endpoint is required' >&2; exit 1;; esac
kubectl --context "$CONTEXT" config view --raw --minify \
  -o jsonpath='{.clusters[0].cluster.certificate-authority-data}' | base64 -d > "$TEMPORARY/ca.crt"
test -s "$TEMPORARY/ca.crt"
openssl req -new -newkey rsa:3072 -nodes -subj "/CN=$IDENTITY" \
  -keyout "$TEMPORARY/client.key" -out "$TEMPORARY/client.csr" 2>/dev/null
REQUEST=$(base64 < "$TEMPORARY/client.csr" | tr -d '\n')
cat <<YAML | kubectl --context "$CONTEXT" create -f -
apiVersion: certificates.k8s.io/v1
kind: CertificateSigningRequest
metadata:
  name: $CSR
spec:
  request: $REQUEST
  signerName: kubernetes.io/kube-apiserver-client
  expirationSeconds: 2592000
  usages:
  - client auth
YAML
# The local administrator approves only the request generated by this invocation.
kubectl --context "$CONTEXT" certificate approve "$CSR"
kubectl --context "$CONTEXT" wait --for=jsonpath='{.status.certificate}' \
  --timeout=60s "certificatesigningrequest/$CSR"
kubectl --context "$CONTEXT" get csr "$CSR" -o jsonpath='{.status.certificate}' \
  | base64 -d > "$TEMPORARY/client.crt"
kubectl --kubeconfig "$TEMPORARY/config" config set-cluster boutique \
  --server="$API" --certificate-authority="$TEMPORARY/ca.crt" --embed-certs=true >/dev/null
kubectl --kubeconfig "$TEMPORARY/config" config set-credentials "$IDENTITY" \
  --client-certificate="$TEMPORARY/client.crt" --client-key="$TEMPORARY/client.key" --embed-certs=true >/dev/null
kubectl --kubeconfig "$TEMPORARY/config" config set-context verifier \
  --cluster=boutique --user="$IDENTITY" --namespace="boutique-$ENVIRONMENT" >/dev/null
kubectl --kubeconfig "$TEMPORARY/config" config use-context verifier >/dev/null
# Verify the actual issued credential can perform the two required read operations.
kubectl --kubeconfig "$TEMPORARY/config" -n "boutique-$ENVIRONMENT" get deployments >/dev/null
kubectl --kubeconfig "$TEMPORARY/config" -n argocd get application "boutique-$ENVIRONMENT" >/dev/null
install -m 600 "$TEMPORARY/config" "$OUTPUT"
printf 'Created %s\n' "$OUTPUT"
openssl x509 -in "$TEMPORARY/client.crt" -noout -enddate
printf 'Upload as Jenkins Secret File credential kubeconfig-%s. Never commit or paste its contents.\n' "$ENVIRONMENT"
